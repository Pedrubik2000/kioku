"""Turn the qmake projects that sip-build generates for PyQt6 into static
CMake library targets, so the bindings can be linked into the iOS and
Android apps.

Usage: gen_pyqt_cmake.py <sip build dir> <output .cmake file>
"""

import re
import sys
from pathlib import Path

QT_COMPONENT = {
    "QtCore": ["Core"],
    "QtGui": ["Core", "Gui"],
    "QtWidgets": ["Core", "Gui", "Widgets"],
    "QtNetwork": ["Core", "Network"],
    "QtSvg": ["Core", "Gui", "Svg"],
}


def read_pro(path: Path) -> dict[str, list[str]]:
    vars: dict[str, list[str]] = {}
    text = path.read_text().replace("\\\n", " ")
    for line in text.splitlines():
        m = re.match(r"^(SOURCES|HEADERS|DEFINES|INCLUDEPATH)\s*\+?=\s*(.*)$", line)
        if m:
            vars.setdefault(m.group(1), []).extend(m.group(2).split())
    return vars


def main() -> None:
    gen_dir = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2])
    lines = ["# Generated by tools/gen_pyqt_cmake.py; do not edit.", ""]
    for module, components in QT_COMPONENT.items():
        pro = gen_dir / module / f"{module}.pro"
        if not pro.exists():
            continue
        v = read_pro(pro)
        mod_dir = pro.parent

        def resolve(p: str) -> str:
            return str((mod_dir / p).resolve())

        sources = [resolve(s) for s in v.get("SOURCES", [])]
        headers = [resolve(h) for h in v.get("HEADERS", [])]
        includes = [
            resolve(i) for i in v.get("INCLUDEPATH", []) if "python3." not in i
        ]
        # Py_LIMITED_API stays: the bindings were generated for the stable ABI
        defines = v.get("DEFINES", [])
        target = f"pyqt6_{module}"
        lines.append(f"add_library({target} STATIC")
        lines += [f'    "{f}"' for f in sources + headers]
        lines.append(")")
        lines.append(f"set_target_properties({target} PROPERTIES AUTOMOC ON)")
        lines.append(f"target_include_directories({target} PRIVATE")
        lines += [f'    "{i}"' for i in includes]
        lines.append("    ${KIOKU_PYTHON_INCLUDE})")
        lines.append(f"target_compile_definitions({target} PRIVATE")
        lines += [f'    "{d}"' for d in defines]
        lines.append(")")
        lines.append(f"target_compile_options({target} PRIVATE -w)")
        libs = " ".join(f"Qt6::{c}" for c in components)
        lines.append(f"target_link_libraries({target} PUBLIC {libs})")
        lines.append(f"list(APPEND KIOKU_PYQT_MODULES {module})")
        lines.append("")
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
