"""Kioku's app icon: two flashcards with a star, flat, on white.

One geometry (a 100×100 design grid) gives every icon file:
  shared/icon/kioku-1024.png                     README
  ios/res/Assets.xcassets/AppIcon.appiconset/icon-1024.png
                                                 iOS app icon (full square, no
                                                 transparency; iOS rounds it)
  android/package/res/drawable/ic_launcher_foreground.xml
                                                 Android adaptive icon layer,
                                                 scaled into the 66 dp safe zone

Usage: python3 shared/tools/make_icon.py   (from anywhere; rewrites the files)
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
BACKGROUND = "#FFFFFF"
BACK_CARD = "#BFDBFE"
FRONT_CARD = "#2563EB"
STAR = "#FFFFFF"

# (box x0, y0, x1, y1, corner radius, rotation in degrees) in the 100 grid
BACK = ((36, 17, 76, 73), 7, 9)
FRONT = ((24, 27, 64, 83), 7, -5)
STAR_CENTER, STAR_OUTER, STAR_INNER, STAR_ROTATION = (44, 56), 14.5, 6.2, -5
STAR_ROUNDING = 2.6  # stroke width that rounds the star's points


def rounded_rect(box, r, angle, steps=12):
    x0, y0, x1, y1 = box
    points = []
    for cx, cy, start in ((x0 + r, y0 + r, 180), (x1 - r, y0 + r, 270),
                          (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90)):
        for i in range(steps + 1):
            a = math.radians(start + 90 * i / steps)
            points.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return rotate(points, (x0 + x1) / 2, (y0 + y1) / 2, angle)


def rotate(points, cx, cy, degrees):
    a = math.radians(degrees)
    c, s = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * c - (y - cy) * s, cy + (x - cx) * s + (y - cy) * c) for x, y in points]


def star():
    cx, cy = STAR_CENTER
    points = []
    for i in range(10):
        radius = STAR_OUTER if i % 2 == 0 else STAR_INNER
        a = math.radians(-90 + STAR_ROTATION + i * 36)
        points.append((cx + radius * math.cos(a), cy + radius * math.sin(a)))
    return points


def png(size):
    big = size * 4
    k = big / 100

    def scaled(points):
        return [(x * k, y * k) for x, y in points]

    img = Image.new("RGB", (big, big), BACKGROUND)
    d = ImageDraw.Draw(img)
    d.polygon(scaled(rounded_rect(*BACK)), fill=BACK_CARD)
    d.polygon(scaled(rounded_rect(*FRONT)), fill=FRONT_CARD)
    # round the star's points: blur a sharp star and threshold it
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).polygon(scaled(star()), fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(STAR_ROUNDING / 2 * k)).point(
        lambda v: 255 if v > 140 else 0)
    img.paste(Image.new("RGB", (big, big), STAR), (0, 0), mask)
    return img.resize((size, size), Image.LANCZOS)


def android_vector():
    # 108 dp canvas; content as large as fits in the 66 dp safe circle
    corners = rounded_rect(*BACK) + rounded_rect(*FRONT)
    scale = 33 / max(math.hypot(x - 50, y - 50) for x, y in corners)
    center = 54

    def path(points):
        pts = [(center + (x - 50) * scale, center + (y - 50) * scale) for x, y in points]
        return "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"

    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by shared/tools/make_icon.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{BACK_CARD}"
        android:pathData="{path(rounded_rect(*BACK))}" />
    <path
        android:fillColor="{FRONT_CARD}"
        android:pathData="{path(rounded_rect(*FRONT))}" />
    <path
        android:fillColor="{STAR}"
        android:strokeColor="{STAR}"
        android:strokeWidth="{STAR_ROUNDING * scale:.2f}"
        android:strokeLineJoin="round"
        android:pathData="{path(star())}" />
</vector>
"""


if __name__ == "__main__":
    icon = png(1024)
    for out in (ROOT / "shared/icon/kioku-1024.png",
                ROOT / "ios/res/Assets.xcassets/AppIcon.appiconset/icon-1024.png"):
        out.parent.mkdir(parents=True, exist_ok=True)
        icon.save(out)
        print(out)
    drawable = ROOT / "android/package/res/drawable/ic_launcher_foreground.xml"
    drawable.parent.mkdir(parents=True, exist_ok=True)
    drawable.write_text(android_vector())
    print(drawable)
